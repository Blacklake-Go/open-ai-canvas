const STORAGE_INSTALLED_APPS_KEY = "tapnow_installed_apps_v1";
const DEFAULT_INSTALLED_IDS = ["voice-performance", "skill-origin-basis", "drama-workshop"];

export function getInstalledAppIds(): string[] {
    try {
        const raw = localStorage.getItem(STORAGE_INSTALLED_APPS_KEY);
        if (raw) {
            const parsed = JSON.parse(raw);
            if (Array.isArray(parsed)) return parsed;
        }
    } catch {}
    return DEFAULT_INSTALLED_IDS;
}

export function isAppInstalled(appId: string): boolean {
    const list = getInstalledAppIds();
    return list.includes(appId);
}

export function toggleAppInstalled(appId: string): boolean {
    const list = getInstalledAppIds();
    const exists = list.includes(appId);
    const next = exists ? list.filter((id) => id !== appId) : [...list, appId];
    try {
        localStorage.setItem(STORAGE_INSTALLED_APPS_KEY, JSON.stringify(next));
    } catch {}
    return !exists;
}
